#!/usr/bin/env node
// Joins the source files in src/ into the one file host pages include: dist/lib.js.
// No dependencies. The files share one scope, wrapped in a single IIFE.
//
//   node build.js           build once
//   node build.js --watch   rebuild whenever a file in src/ changes

'use strict';

var fs = require('fs');
var path = require('path');

// Order matters: init.js must come first (it captures document.currentScript),
// and main.js last (it starts everything once all functions are defined).
var FILES = ['init.js', 'extract.js', 'tree.js', 'gemini.js', 'search.js', 'preview.js', 'widget.js', 'main.js'];

var SRC = path.join(__dirname, 'src');
var OUT = path.join(__dirname, 'dist', 'lib.js');

var BANNER = [
  '/*',
  ' * PageLens — a drop-in chat widget that points users to the right place on a page.',
  ' *',
  ' * Include it with a script tag that marks the START of the AI region:',
  ' *   <script src="lib.js" data-start data-api-key="..." data-provider="gemini"></script>',
  ' * and close the region with:',
  ' *   <script data-pagelens-end></script>',
  ' *',
  ' * GENERATED by build.js from the files in src/. Edit those, not this file.',
  ' */'
].join('\n');

function indent(text) {
  return text.split('\n').map(function (line) { return line ? '  ' + line : line; }).join('\n');
}

function build() {
  var parts = FILES.map(function (name) {
    var code = fs.readFileSync(path.join(SRC, name), 'utf8').replace(/\s+$/, '');
    return indent('// ---- src/' + name + ' ----\n\n' + code);
  });
  var output = BANNER + '\n(function () {\n  \'use strict\';\n\n' + parts.join('\n\n') + '\n})();\n';
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, output);
  console.log('Built ' + path.relative(__dirname, OUT) + ' (' + output.length + ' bytes) at ' +
    new Date().toLocaleTimeString());
}

build();

if (process.argv.includes('--watch')) {
  console.log('Watching src/ for changes. Press Ctrl+C to stop.');
  var timer = null;
  // A running watcher keeps the FILES list it started with, so changes to this
  // script itself need a restart.
  fs.watch(__filename, function () {
    console.warn('build.js changed: stop this watcher (Ctrl+C) and start it again to pick up the change.');
  });
  fs.watch(SRC, function () {
    // Editors often write a file in several steps; wait for them to finish.
    clearTimeout(timer);
    timer = setTimeout(function () {
      try { build(); } catch (err) { console.error('Build failed:', err.message); }
    }, 100);
  });
}
